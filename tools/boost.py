"""Halim Jarrar, 2026. GPL-3.0-or-later with the additional permission described in NOTICES.md (linking with the Helix MP3 decoder). Volume Boost reference (v0.9.5): digital gain plus a
stateless soft limiter, applied to 16-bit samples before the 8-bit output
stage. Generates player/src/boost_table.h; the GBA code (boost.h) and this
file must give the same result for every input (tests/test_boost.py).

    v = (x * GAIN[level]) >> 8                 (arithmetic shift)
    |v| <= KNEE: unchanged
    |v| >  KNEE: u = |v| - KNEE, i = u >> 10, f = u & 1023
                 y = CURVE[i] + (((CURVE[i+1] - CURVE[i]) * f) >> 10)   (i < 256)
                 y = CURVE[256]                                          (i >= 256)
                 v = sign(v) * (KNEE + y)
CURVE[i] = round(R * tanh(i*1024 / R)), R = 32767 - KNEE: slope 1 at the
knee (no corner), approaching full scale smoothly.
"""
import math

LEVELS = (0, 3, 6, 9)                    # dB
GAIN = (256, 362, 512, 724)              # Q8: round(256 * 10^(dB/20))
KNEE = 23197                             # -3 dBFS
RANGE = 32767 - KNEE
STEP_BITS = 10
CURVE = [int(round(RANGE * math.tanh((i << STEP_BITS) / RANGE))) for i in range(257)]


def boost(x, level):
    """One 16-bit (or wider stereo-sum) sample at level 0..3."""
    g = GAIN[level]
    if g == 256:
        return x
    v = (x * g) >> 8
    a = -v if v < 0 else v
    if a <= KNEE:
        return v
    u = a - KNEE
    i = u >> STEP_BITS
    y = CURVE[256] if i >= 256 else CURVE[i] + (((CURVE[i + 1] - CURVE[i]) * (u & 1023)) >> STEP_BITS)
    y += KNEE
    return -y if v < 0 else y


def c_table():
    return ('/* Generated by tools/boost.py; tests/test_boost.py checks it. Halim Jarrar, 2026. GPL-3.0-or-later with the additional permission described in NOTICES.md (linking with the Helix MP3 decoder). */\n'
            f'#define BOOST_KNEE {KNEE}\n#define BOOST_GAINS {{{",".join(map(str, GAIN))}}}\n'
            '#define BOOST_CURVE {\\\n' + ',\\\n'.join(' ' + ','.join(map(str, CURVE[i:i + 16])) for i in range(0, 257, 16)) + '}\n')


if __name__ == '__main__':
    import sys
    sys.stdout.write(c_table())
