"""Halim Jarrar, 2026. GPL-3.0-or-later with the additional permission described in NOTICES.md (linking with the Helix MP3 decoder). Resampling filters for converting songs on the GBA
(player/src/convert.c): polyphase windowed-sinc FIR, 16 taps, 256 phases,
Q14 (each phase sums to 16384: unit gain at DC). One table for sources at or
below 32768 Hz (cutoff at 45% of the source rate), one each for 44100 and
48000 Hz (cutoff at 45% of 32768 Hz, below the output's Nyquist frequency),
and RS_DOWN for 32768 -> 32000 Hz (GAC -> MP3; cutoff at 45% of 32000 Hz).
Usage: python3 tools/resample_tables.py > player/src/resample_tables.h"""
import numpy as np
TAPS, PHASES, OUT = 16, 256, 32768

def table(rate, out=OUT):
    fc = 0.45 * min(1.0, out / rate)          # cycles per input sample
    rows = []
    for p in range(PHASES):
        t = np.arange(TAPS) - (TAPS // 2 - 1) - p / PHASES   # tap k reads input base - 7 + k
        w = np.i0(7.0 * np.sqrt(np.clip(1 - (t / (TAPS / 2)) ** 2, 0, 1))) / np.i0(7.0)   # Kaiser, beta 7
        h = 2 * fc * np.sinc(2 * fc * t) * w
        q = np.round(h / h.sum() * 16384).astype(int)
        q[TAPS // 2 - 1 + (p >= PHASES // 2)] += 16384 - q.sum()     # exact unit gain
        rows.append(q)
    return rows

def c_source():
    out = ['/* Generated by tools/resample_tables.py; tests/test_convert.py checks it. Halim Jarrar, 2026. GPL-3.0-or-later with the additional permission described in NOTICES.md (linking with the Helix MP3 decoder). */',
           f'#define RS_TAPS {TAPS}', f'#define RS_PHASES {PHASES}']
    for name, rate, out_rate in (('RS_UP', 32768, OUT), ('RS_44100', 44100, OUT), ('RS_48000', 48000, OUT), ('RS_DOWN', 32768, 32000)):
        rows = table(rate, out_rate)
        out.append(f'static const int16_t {name}[{PHASES}][{TAPS}] __attribute__((aligned(4)))={{\n' + ',\n'.join(' {' + ','.join(map(str, r)) + '}' for r in rows) + '};')
    return '\n'.join(out) + '\n'

if __name__ == '__main__':
    import sys
    sys.stdout.write(c_source())
